#!/usr/bin/env python3
"""Generate skin/tokens.uss from design/tokens.json.

Every token becomes a USS custom property on :root, prefixed --fms- so it never
collides with Football Manager's own variables. Run it after changing tokens.json;
scripts/install.sh runs it for you.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
TARGET = ROOT / "skin" / "tokens.uss"

# Groups whose numbers are pixel lengths in USS.
PIXEL_GROUPS = {"radius", "space", "font-size"}


def uss_value(group: str, value) -> str:
    if isinstance(value, (int, float)) and group in PIXEL_GROUPS:
        return f"{value}px"
    if group == "font-family":
        return f'"{value}"'
    return str(value)


def build() -> str:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "/* Generated by scripts/build-tokens.py from design/tokens.json. Don't edit by hand. */",
        "",
        ":root {",
    ]
    for group, entries in tokens.items():
        if group.startswith("$"):
            continue
        lines.append(f"    /* {group} */")
        for name, value in entries.items():
            lines.append(f"    --fms-{group}-{name}: {uss_value(group, value)};")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    output = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != output:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run scripts/build-tokens.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(output, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
